/** Generates app/themes.css from app/globals.css.
 * Run from apps/web after changing any colour in globals.css:
 *   node scripts/generate-themes.ts
 * lib/themes.test.ts fails if the committed file is stale. */
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import postcss from 'postcss';
import {THEMES,themeSelector,themeValue} from '../lib/themes.ts';

export function generateThemes(source:string):string {
  const root=postcss.parse(source);
  let out='/* GENERATED by scripts/generate-themes.ts from globals.css. Do not edit by hand. */\n';
  for(const theme of THEMES){
    if(theme.id==='nebula')continue;
    const emit=(rule:postcss.Rule)=>{
      if(rule.parent?.type==='atrule'&&/keyframes/.test((rule.parent as postcss.AtRule).name))return '';
      const changed:string[]=[];
      rule.walkDecls(decl=>{const value=themeValue(decl.prop,decl.value,theme.id);if(value!==decl.value)changed.push(`${decl.prop}:${value}${decl.important?'!important':''}`)});
      return changed.length?`${rule.selectors.map(s=>themeSelector(s,theme.id)).join(',')}{${changed.join(';')}}`:'';
    };
    out+=`\n/* ${theme.name} */\n`;
    for(const node of root.nodes){
      if(node.type==='rule'){const css=emit(node);if(css)out+=css+'\n'}
      else if(node.type==='atrule'&&node.name==='media'){
        let inner='';node.walkRules(rule=>{inner+=emit(rule)});
        if(inner)out+=`@media${node.params}{${inner}}\n`;
      }
    }
  }
  return out;
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
  const css=fileURLToPath(new URL('../app/globals.css',import.meta.url));
  const target=fileURLToPath(new URL('../app/themes.css',import.meta.url));
  writeFileSync(target,generateThemes(readFileSync(css,'utf8')));
  console.log('Wrote',target);
}
